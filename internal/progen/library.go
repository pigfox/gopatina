package progen

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// Library checks (RFC 0014). For program k, LibraryPackage is a Go package
// whose exported API covers what a library crate exposes: integer
// arithmetic, strings, slices, a struct with a value and a pointer method,
// an error result with a sentinel and a wrapped error, and a constant.
// LibraryCheckGo calls it on fixed inputs and prints the results;
// LibraryCheckRust is a hand-written-style Rust program that calls the
// crate GoPatina generates from the package and prints the same, so a
// difference is a defect of the library crate's API or code.

// LibraryName is the package (and crate) name of the library checks.
const LibraryName = "glib"

// libraryStream is the random stream of program k's library check.
func libraryStream(seed, k uint64) *rand.Rand {
	return rand.New(rand.NewPCG(seed^0xd1b54a32d192ed03, k))
}

type libGen struct {
	r   *rand.Rand
	ops []string // the arithmetic of F
	add int      // P.Grow's step
	rep int      // S's repeat count
	mod int      // E's modulus
}

func newLibGen(seed uint64, k int) *libGen {
	r := libraryStream(seed, uint64(k))
	ops := []string{"+", "-", "*", "^", "|", "&"}
	g := &libGen{r: r, add: 1 + r.IntN(9), rep: 1 + r.IntN(3), mod: 2 + r.IntN(4)}
	for range 3 {
		g.ops = append(g.ops, ops[r.IntN(len(ops))])
	}
	return g
}

// LibraryPackage returns the Go source of program k's library package.
func LibraryPackage(seed uint64, k int) string {
	g := newLibGen(seed, k)
	return fmt.Sprintf(`// Code generated by internal/progen. DO NOT EDIT.

// Package glib is a library GoPatina translates into a Rust crate (RFC 0014).
package glib

import (
	"errors"
	"fmt"
	"strings"
)

// Limit is a constant of the API.
const Limit = %d

// ErrNeg is returned for a negative input.
var ErrNeg = errors.New("glib: negative")

// P is a struct of the API.
type P struct {
	A, B int
	Tag  string
}

// Sum reads its copy.
func (p P) Sum() int { return p.A %s p.B }

// Grow changes the struct it is called on.
func (p *P) Grow(by int) {
	p.A += by
	p.B += %d
}

// F computes on integers, wrapping as Go does.
func F(x, y int) int { return ((x %s y) %s Limit) %s x }

// S builds a string.
func S(s string, n int) string {
	return strings.Repeat(s, %d) + fmt.Sprint(n)
}

// V keeps the slice it is given, grown by one.
func V(xs []int, x int) []int {
	xs = append(xs, x)
	return xs
}

// Total reads a slice.
func Total(xs []int) int {
	t := 0
	for _, x := range xs {
		t += x
	}
	return t
}

// E fails for a negative input, and for a multiple of %d.
func E(x int) (int, error) {
	if x < 0 {
		return 0, ErrNeg
	}
	if x%%%d == 0 {
		return 0, fmt.Errorf("glib: %%d: %%w", x, ErrNeg)
	}
	return x * 2, nil
}
`, 3+g.r.IntN(50), g.ops[0], g.add, g.ops[1], g.ops[2], g.ops[0], g.rep, g.mod, g.mod)
}

// libraryInputs are the fixed inputs both checks use.
func libraryInputs(seed uint64, k int) (xs []int64, words []string) {
	r := rand.New(rand.NewPCG(seed^0x8bb84b93962eacc9, uint64(k)))
	for range 4 {
		xs = append(xs, interestingOrSmall(r))
	}
	all := []string{"", "go", "ΟΔΟΣ", "a b"}
	words = append(words, all[r.IntN(len(all))], all[r.IntN(len(all))])
	return xs, words
}

func interestingOrSmall(r *rand.Rand) int64 {
	if r.IntN(2) == 0 {
		return interesting[r.IntN(len(interesting))]
	}
	return r.Int64N(41) - 20
}

// LibraryCheckGo returns a Go program that calls the library package and
// prints the results, one line each.
func LibraryCheckGo(seed uint64, k int, importPath string) string {
	xs, words := libraryInputs(seed, k)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/progen. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"errors\"\n\t\"fmt\"\n\n\t%q\n)\n\nfunc main() {\n", importPath)
	b.WriteString("\tfmt.Println(glib.Limit)\n")
	for i := 0; i+1 < len(xs); i++ {
		fmt.Fprintf(&b, "\tfmt.Println(glib.F(%d, %d))\n", xs[i], xs[i+1])
	}
	for i, w := range words {
		fmt.Fprintf(&b, "\tfmt.Println(glib.S(%q, %d))\n", w, xs[i])
	}
	fmt.Fprintf(&b, "\tp := glib.P{A: %d, B: %d, Tag: %q}\n\tp.Grow(%d)\n\tfmt.Println(p.Sum(), p.A, p.B, p.Tag)\n", xs[0], xs[1], words[0], xs[2])
	b.WriteString("\tvar xs []int\n")
	for _, x := range xs {
		fmt.Fprintf(&b, "\txs = glib.V(xs, %d)\n", x)
	}
	b.WriteString("\tfmt.Println(len(xs), xs, glib.Total(xs))\n")
	for _, x := range append(xs, -1, 0) {
		fmt.Fprintf(&b, "\tif v, err := glib.E(%d); err != nil {\n\t\tfmt.Println(err, errors.Is(err, glib.ErrNeg), err == glib.ErrNeg)\n\t} else {\n\t\tfmt.Println(v)\n\t}\n", x)
	}
	b.WriteString("}\n")
	return b.String()
}

// LibraryCheckRust returns a Rust program that calls the crate GoPatina
// generates from the library package and prints what LibraryCheckGo's
// program prints.
func LibraryCheckRust(seed uint64, k int) string {
	xs, words := libraryInputs(seed, k)
	var b strings.Builder
	b.WriteString("// Code generated by internal/progen. DO NOT EDIT.\n\n")
	b.WriteString("fn show(xs: &[i64]) -> String {\n    let parts: Vec<String> = xs.iter().map(|x| x.to_string()).collect();\n    format!(\"[{}]\", parts.join(\" \"))\n}\n\n")
	b.WriteString("fn main() {\n    println!(\"{}\", glib::LIMIT);\n")
	for i := 0; i+1 < len(xs); i++ {
		fmt.Fprintf(&b, "    println!(\"{}\", glib::f(%s, %s));\n", rustInt(xs[i]), rustInt(xs[i+1]))
	}
	for i, w := range words {
		fmt.Fprintf(&b, "    println!(\"{}\", glib::s(%s, %s));\n", rustString(w), rustInt(xs[i]))
	}
	fmt.Fprintf(&b, "    let mut p = glib::P {\n        a: %s,\n        b: %s,\n        tag: %s.to_string(),\n    };\n    p.grow(%s);\n    println!(\"{} {} {} {}\", p.sum(), p.a, p.b, p.tag);\n",
		rustInt(xs[0]), rustInt(xs[1]), rustString(words[0]), rustInt(xs[2]))
	b.WriteString("    let mut xs: Vec<i64> = Vec::new();\n")
	for _, x := range xs {
		fmt.Fprintf(&b, "    xs = glib::v(xs, %s);\n", rustInt(x))
	}
	b.WriteString("    println!(\"{} {} {}\", xs.len(), show(&xs), glib::total(&xs));\n")
	b.WriteString("    let neg = glib::err_neg();\n")
	for _, x := range append(xs, -1, 0) {
		fmt.Fprintf(&b, "    match glib::e(%s) {\n        Ok(v) => println!(\"{v}\"),\n        Err(e) => println!(\"{} {} {}\", e, e.is(&neg), e == neg),\n    }\n", rustInt(x))
	}
	b.WriteString("}\n")
	return b.String()
}

// rustInt writes an i64 literal; the most negative one needs i64::MIN.
func rustInt(x int64) string {
	if x == -1<<63 {
		return "i64::MIN"
	}
	return fmt.Sprint(x)
}

// rustString writes a string literal.
func rustString(s string) string { return fmt.Sprintf("%q", s) }
