// Toolchain is the Rust release every emitted crate pins, and MSRV the
// minimum Rust version its code needs (RFC 0003).
const (
	Toolchain = "1.93.0"
	MSRV      = "1.85"
)

// ManifestName is the file, beside the crate's other files, that lists the
// sha256 of each, in sha256sum format.
const ManifestName = "gopatina-manifest.sha256"

// Options control the crate.
type Options struct {
	// Target is the Rust target triple the crate builds for.
	Target string
	// Version is the GoPatina version, recorded in Cargo.toml.
	Version string
	// CrateName overrides the crate's name (-crate-name), and CrateVersion
	// sets its version (-version vX.Y.Z; default 0.0.0) (RFC 0014).
	CrateName, CrateVersion string
}

// A File is one file of the crate, at a slash-separated relative path.
type File struct {
	Path string
	Data []byte
}

// A Crate is the emitted cargo crate.
type Crate struct {
	Name   string // the package and binary name
	Target string // the Rust target triple it builds for
	Files  []File // sorted by path, without the manifest
	// Notes are the emitter's own decisions (loop specialization), in
	// source order, for -explain.
	Notes []Note
	// Library: a library crate (RFC 0014), with no binary.
	Library bool
}

// Emit translates pkg, already checked by subset and borrow, into a crate.
func Emit(pkg *load.Package, res *borrow.Result, opt Options) *Crate {
	errs, _ := subset.Errors(pkg)
	mainRS, rtRS, notes, modules, api := source(pkg, res, errs)
	name := CrateName(pkg.Dir)
	if api != nil {
		name = libraryName(pkg)
	}
	if opt.CrateName != "" {
		name = opt.CrateName
	}
	version := strings.TrimPrefix(opt.CrateVersion, "v")
	if version == "" {
		version = "0.0.0"
	}
	c := &Crate{Name: name, Target: opt.Target, Notes: notes, Library: api != nil}
	main := "src/main.rs"
	if api != nil {
		// A library (RFC 0014): no start-up, so no Go panic hook, and a
		// panic carries Go's message without the hook's marker.
		main = "src/lib.rs"
		mainRS, rtRS = unmark(mainRS), unmark(rtRS)
		for i := range modules {
			modules[i].Text = unmark(modules[i].Text)
		}
		from := pkg.ImportPath
		if from == "" {
			from = "package " + pkg.Name
		}
		c.add("api.txt", apiText(name, version, from, mainRS, api.notes))
	}
	c.add("Cargo.toml", cargoToml(name, version, api != nil, opt))
	c.add("Cargo.lock", cargoLock(name, version))
	c.add("rust-toolchain.toml", toolchainToml(opt.Target))
	c.add(".cargo/config.toml", cargoConfig(opt.Target))
	c.add(main, mainRS)
	if rtRS != "" {
		c.add("src/rt.rs", rtRS)
	}
	for _, m := range modules {
		c.add(m.Path, m.Text)
	}
	sort.Slice(c.Files, func(i, j int) bool { return c.Files[i].Path < c.Files[j].Path })
	return c
}

func (c *Crate) add(path, data string) { c.Files = append(c.Files, File{path, []byte(data)}) }

// libraryName is a library crate's default name (RFC 0014): the last
// element of its import path (or its directory, for a package loaded from
// source), with '-' turned into '_' as cargo's conventions have it.
func libraryName(pkg *load.Package) string {
	base := pkg.ImportPath
	if base == "" {
		base = pkg.Dir
	}
	return strings.ReplaceAll(CrateName(base[strings.LastIndex(base, "/")+1:]), "-", "_")
}

// unmark removes the marker a program's panic hook strips from GoPatina's
// own panic messages: a library has no hook (RFC 0014). A panic! whose
// only argument is a string literal was broken over lines because, with the
// marker, it did not fit; rustfmt joins it again once it does.
func unmark(s string) string {
	lines := strings.Split(strings.ReplaceAll(s, "gopatina-user-panic:", ""), "\n")
	var out []string
	for i := 0; i < len(lines); i++ {
		l := lines[i]
		if strings.HasSuffix(l, "panic!(") && i+2 < len(lines) {
			lit := strings.TrimSpace(lines[i+1])
			end := strings.TrimSpace(lines[i+2])
			if strings.HasPrefix(lit, "\"") && strings.HasSuffix(lit, "\"") && strings.HasPrefix(end, ")") {
				if one := l + lit + end; len(one) <= maxWidth {
					out = append(out, one)
					i += 2
					continue
				}
			}
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}

// CrateName derives a cargo package name from the package directory.
func CrateName(dir string) string {
	base := strings.ToLower(filepath.Base(dir))
	var b strings.Builder
	for _, r := range base {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	name := b.String()
	if name == "" || name[0] < 'a' || name[0] > 'z' {
		name = "app_" + name
	}
	return name
}

func cargoToml(name, version string, lib bool, opt Options) string {
	head := fmt.Sprintf(`# Generated by GoPatina %s (gopatina build -emit-rust).
[package]
name = %q
version = %q
edition = "2024"
rust-version = %q
publish = false

[dependencies]
`, opt.Version, name, version, MSRV)
	if lib {
		// A workspace ignores a member's profiles, so the crate states what
		// its users set instead (RFC 0014).
		return head + fmt.Sprintf(`
# Go integers wrap on overflow; with overflow checks off, Rust's do too. In
# release builds they are off by default. A workspace that builds this crate
# in its dev profile turns them off for it in its own Cargo.toml:
#
#   [profile.dev.package.%s]
#   overflow-checks = false
`, name)
	}
	return head + `
# Go integers wrap on overflow; with overflow checks off, Rust's do too.
[profile.dev]
overflow-checks = false

# Reproducible builds (docs/REPRODUCIBLE.md): the same crate and toolchain
# give a byte-identical binary.
[profile.release]
codegen-units = 1
debug = false
strip = true
incremental = false
overflow-checks = false
`
}

func cargoLock(name, version string) string {
	return fmt.Sprintf(`# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = %q
version = %q
`, name, version)
}

func toolchainToml(target string) string {
	return fmt.Sprintf(`# Pinned toolchain, so the crate builds the same way later (RFC 0003).
[toolchain]
channel = %q
profile = "minimal"
targets = [%q]
`, Toolchain, target)
}

func cargoConfig(target string) string {
	return fmt.Sprintf(`# An explicit target, so the build does not depend on the host's default.
[build]
target = %q
`, target)
}

// Manifest returns gopatina-manifest.sha256 for the crate's files.
func (c *Crate) Manifest() []byte {
	var b strings.Builder
	for _, f := range c.Files {
		sum := sha256.Sum256(f.Data)
		fmt.Fprintf(&b, "%s  %s\n", hex.EncodeToString(sum[:]), f.Path)
	}
	return []byte(b.String())
}

// Write writes the crate and its manifest into dir. dir must be empty, not
// exist, or hold a crate GoPatina wrote earlier (one with a manifest).
func (c *Crate) Write(dir string) error {
	if err := checkDir(dir); err != nil {
		return err
	}
	for _, f := range append(c.Files, File{ManifestName, c.Manifest()}) {
		path := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, f.Data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// checkDir refuses to write into a directory that holds files GoPatina did
// not write.
func checkDir(dir string) error {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if len(entries) == 0 {
		return nil
	}
	if _, err := os.Stat(filepath.Join(dir, ManifestName)); err != nil {
		return fmt.Errorf("%s is not empty and was not written by gopatina (it has no %s); choose another -o directory", dir, ManifestName)
	}
	return nil
}
