// Command gencase writes internal/emit/casetables.go: Go's case mapping and
// simple folding tables (package unicode of the Go toolchain that runs it),
// as the Rust source the emitter writes into rt.rs for strings.ToLower,
// strings.ToUpper and strings.EqualFold. The tables are committed, so the
// emitted crate does not depend on the toolchain that runs GoPatina; run it
// with the Go release GoPatina's oracle uses (go generate ./internal/emit).
package main

import (
	"fmt"
	"os"

	"github.com/pigfox/gopatina/internal/emit/internal/casetab"
)

func main() {
	src := "// Code generated by gencase from Go's unicode " + casetab.Version() + "; DO NOT EDIT.\n\npackage emit\n\n" +
		"// UnicodeVersion is the Unicode version of the case tables the emitted\n// crates use (Go 1.27's, whatever toolchain runs GoPatina).\nconst UnicodeVersion = " + fmt.Sprintf("%q", casetab.Version()) + "\n\n" +
		"// caseTables is the Rust source of Go's case tables.\nconst caseTables = " + fmt.Sprintf("%q", casetab.Rust()) + "\n"
	if err := os.WriteFile(os.Args[1], []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
