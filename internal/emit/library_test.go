package emit

import (
	"strings"
	"testing"

	"github.com/pigfox/gopatina/internal/borrow"
	"github.com/pigfox/gopatina/internal/load"
	"github.com/pigfox/gopatina/internal/subset"
)

// TestLibraryOptions checks a library loaded from source alone (no module):
// its name comes from its directory, -crate-name and -version override the
// defaults, and an exported struct holding an error value is not Debug
// (RFC 0014).
func TestLibraryOptions(t *testing.T) {
	src := "package stats\n\ntype Run struct {\n\tN   int\n\terr error\n}\n\nfunc Count(r Run) int { return r.N }\n"
	pkg, err := load.Source("/x/my-stats", "stats.go", src, "go1.25")
	if err != nil {
		t.Fatal(err)
	}
	if ds := subset.Check(pkg); len(ds) > 0 {
		t.Fatal(ds)
	}
	res, ds := borrow.Check(pkg)
	if len(ds) > 0 {
		t.Fatal(ds)
	}
	c := Emit(pkg, res, Options{Target: goldenTarget, Version: "devel"})
	files := map[string]string{}
	for _, f := range c.Files {
		files[f.Path] = string(f.Data)
	}
	if c.Name != "my_stats" || !c.Library || !strings.Contains(files["api.txt"], "generated by GoPatina from package stats") {
		t.Errorf("crate %q, library %v, api.txt:\n%s", c.Name, c.Library, files["api.txt"])
	}
	if strings.Contains(files["src/lib.rs"], "Debug") {
		t.Error("a struct holding an error value derives Debug")
	}
	c = Emit(pkg, res, Options{Target: goldenTarget, Version: "devel", CrateName: "stats", CrateVersion: "v1.2.3"})
	for _, f := range c.Files {
		if f.Path == "Cargo.toml" && (!strings.Contains(string(f.Data), "name = \"stats\"") || !strings.Contains(string(f.Data), "version = \"1.2.3\"")) {
			t.Errorf("Cargo.toml:\n%s", f.Data)
		}
	}
}
