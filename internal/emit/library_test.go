// TestLibraryOptions checks a library loaded from source alone (no module):
// its name comes from its directory, -crate-name and -version override the
// defaults, and an exported struct holding an error value is not Debug
// (RFC 0014).
func TestLibraryOptions(t *testing.T) {
	src := "package stats\n\ntype Run struct {\n\tN   int\n\terr error\n}\n\nfunc Count(r Run) int { return r.N }\n"
	pkg, err := load.Source("/x/my-stats", "stats.go", src, "go1.25")
	if err != nil {
		t.Fatal(err)
	}
	if ds := subset.Check(pkg); len(ds) > 0 {
		t.Fatal(ds)
	}
	res, ds := borrow.Check(pkg)
	if len(ds) > 0 {
		t.Fatal(ds)
	}
	c := Emit(pkg, res, Options{Target: goldenTarget, Version: "devel"})
	files := map[string]string{}
	for _, f := range c.Files {
		files[f.Path] = string(f.Data)
	}
	if c.Name != "my_stats" || !c.Library || !strings.Contains(files["api.txt"], "generated by GoPatina from package stats") {
		t.Errorf("crate %q, library %v, api.txt:\n%s", c.Name, c.Library, files["api.txt"])
	}
	if strings.Contains(files["src/lib.rs"], "Debug") {
		t.Error("a struct holding an error value derives Debug")
	}
	c = Emit(pkg, res, Options{Target: goldenTarget, Version: "devel", CrateName: "stats", CrateVersion: "v1.2.3"})
	for _, f := range c.Files {
		if f.Path == "Cargo.toml" && (!strings.Contains(string(f.Data), "name = \"stats\"") || !strings.Contains(string(f.Data), "version = \"1.2.3\"")) {
			t.Errorf("Cargo.toml:\n%s", f.Data)
		}
	}
}

// TestCheckAPI checks -api-check's comparison and cargo's compatibility
// rule (RFC 0014).
func TestCheckAPI(t *testing.T) {
	head := func(v string) string {
		return "# The API of crate x " + v + ", generated by GoPatina from x (RFC 0014).\n# notes\n"
	}
	old := head("1.2.3") + "pub fn a(s: &str) -> String\npub fn b(n: i64) -> i64\n    why: owned\n"
	cur := head("1.3.0") + "pub fn a(s: &str) -> String\npub fn b(n: i64) -> i64\n    why: changed note\npub fn c() -> i64\n"
	if ch := CheckAPI(old, cur); len(ch.Removed) != 0 || len(ch.Added) != 1 || ch.Breaking {
		t.Errorf("an added item and a changed note: %+v", ch)
	}
	changed := head("1.3.0") + "pub fn a(s: String) -> String\npub fn b(n: i64) -> i64\n"
	if ch := CheckAPI(old, changed); len(ch.Removed) != 1 || len(ch.Added) != 1 || !ch.Breaking {
		t.Errorf("a changed signature in a compatible version: %+v", ch)
	}
	if ch := CheckAPI(old, strings.Replace(changed, "1.3.0", "2.0.0", 1)); ch.Breaking {
		t.Errorf("a changed signature in a new major version: %+v", ch)
	}
	for _, tc := range []struct {
		a, b string
		want bool
	}{
		{"1.2.3", "1.9.0", true}, {"1.2.3", "2.0.0", false},
		{"0.2.3", "0.2.9", true}, {"0.2.3", "0.3.0", false},
		{"0.0.3", "0.0.3", true}, {"0.0.3", "0.0.4", false},
	} {
		if got := compatible(apiVersion(head(tc.a)), apiVersion(head(tc.b))); got != tc.want {
			t.Errorf("compatible(%s, %s) = %v", tc.a, tc.b, got)
		}
	}
	if v := apiVersion("# an api.txt from before versions\n"); v != [3]int{} {
		t.Errorf("no version: %v", v)
	}
}
